notebook = {
    "nbformat": 4, "nbformat_minor": 5,
    "metadata": {"colab": {"name": "Convert_Alphabet_FP32.ipynb"}, "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"}},
    "cells": [
        markdown("# Chuyển BiGRU Alphabet sang TFLite FP32\n\nMở notebook trong Google Colab, chọn **Runtime → Run all**, upload checkpoint khi được hỏi, rồi gửi lại file ZIP kết quả.\n\nKiến trúc lấy nguyên từ VOYA-Collector; model hidden=64, 2 GRU layers, dropout=0.3 được kiểm chứng bằng weights. Nhãn lấy từ checkpoint. Không quantize/retrain. Chuỗi test có cấu trúc landmark kiểm tra độ khớp số học; accuracy thực cần thêm `test_data.npz`.\n\nDependencies chỉ cài trong Colab. Không cần bật GPU. [LiteRT Torch](https://github.com/google-ai-edge/litert-torch), [torch/torchao compatibility](https://github.com/pytorch/ao/issues/2919)."),
        cell(install),
        cell(upload),
        markdown("## Python converter độc lập\nCell dưới ghi file Python; có thể thu gọn cell sau khi chạy."),
        cell("%%writefile /content/convert_alphabet_colab.py\n" + standalone),
        cell(run),
    ],
}
path = DEST / "Convert_Alphabet_FP32.ipynb"
for index, c in enumerate(notebook["cells"]):
    c["id"] = f"alphabet-{index:02d}"
path.write_text(json.dumps(notebook, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
for c in notebook["cells"]:
    if c["cell_type"] == "code":
        source = ''.join(c["source"])
        if source.startswith("%%writefile"):
            source = source.split('\n', 1)[1]
        ast.parse(source)
print(f"Created {script_path.relative_to(ROOT)} ({script_path.stat().st_size} bytes)")
print(f"Created {path.relative_to(ROOT)} ({path.stat().st_size} bytes); Python cells parse successfully")
