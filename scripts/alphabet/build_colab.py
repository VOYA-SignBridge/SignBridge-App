"""Generate a standalone converter and a Colab notebook from the reviewed source.

Uses only stdlib; does not install conversion dependencies or execute conversion.
"""
import ast
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT / "scripts/alphabet/colab"
DEST.mkdir(exist_ok=True)

def read(name):
    return (ROOT / name).read_text(encoding="utf-8")

sources = {
    name: read(name) for name in (
        "VOYA-Collector/processed/train_utils/models/base.py",
        "VOYA-Collector/processed/train_utils/models/bigru_attention.py",
        "VOYA-Collector/processed/shared/normalization.py",
    )
}
code = read("scripts/alphabet/deploy.py")
code = code.replace("from __future__ import annotations\n", "")
code = code.replace('ROOT = Path(__file__).resolve().parents[2]', 'ROOT = Path(__file__).resolve().parent')
code = code.replace('sys.path.insert(0, str(ROOT / "VOYA-Collector"))\n', '')
code = code.replace('from processed.train_utils.models.bigru_attention import BiGRUAttentionModel\n', '')
code = code.replace('from processed.shared.normalization import normalize_hands_vector_126\n', '')
code = code.replace('p.add_argument("--contract", default="scripts/alphabet/deployment_contract.json")',
                    'p.add_argument("--contract", help="Optional override of the embedded, hash-pinned contract")')
code = code.replace('contract = json.loads(local(args.contract).read_text(encoding="utf-8"))',
                    'contract = json.loads(local(args.contract).read_text(encoding="utf-8")) if args.contract else json.loads(EMBEDDED_CONTRACT_JSON)')
code = code.replace('"resolvedModelConfig": model.get_config(),', '"modelSourceSha256": MODEL_SOURCE_SHA256, "resolvedModelConfig": model.get_config(),')

parts = [
    '# Generated by scripts/alphabet/build_colab.py. Standalone, original BiGRU architecture.\n',
    '# Run on Colab/Linux: python convert_alphabet_colab.py convert --output-dir output_run_1\n',
    'from __future__ import annotations\n',
]
for name, source in sources.items():
    source = source.replace('from .base import SignLanguageModel, initialize_kaiming\n', '')
    parts += [f'\n# Original source: {name}\n', source, '\n']
parts += [
    '\nEMBEDDED_CONTRACT_JSON = ' + repr(read("scripts/alphabet/deployment_contract.json")) + '\n',
    'MODEL_SOURCE_SHA256 = ' + repr({name: hashlib.sha256(source.encode()).hexdigest() for name, source in sources.items()}) + '\n',
    code,
]
standalone = ''.join(parts)
ast.parse(standalone)
script_path = DEST / "convert_alphabet_colab.py"
script_path.write_text(standalone, encoding="utf-8")

def markdown(text):
    return {"cell_type": "markdown", "metadata": {}, "source": text.splitlines(keepends=True)}

def cell(text):
    return {"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [], "source": text.splitlines(keepends=True)}

